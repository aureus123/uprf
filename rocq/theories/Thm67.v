Lemma C6_sound F : C6 F -> PrimNN F.
Proof. by move: F; sound. Qed.

(* Theorem 6.7: F = <1, E, F^+, FG, F^box> is suitable *)
Theorem Theorem_6_7 : suitable basis6.
Proof. by move=> F; split; [exact: C6_sound | exact: PrimNN_sub_C6]. Qed.

(* Robinson [15, Sec. 7, Theorem 3]: <S, E, F + G, FG, F^box> is suitable *)
Theorem Robinson_1947_sec7_thm3 : suitable basisRobinson.
Proof.
by move=> F; split; [exact: Robinson_sound | move/PrimNN_sub_C6; exact: C6_sub_CR].
Qed.

(* footnote 3: x - y stands for any function d(x, y) equal to x - y whenever x >= y *)
Definition is_difference (d : nat -> nat -> nat) : Prop := forall a b, b <= a -> d a b = a - b.

Definition opDiff (d : nat -> nat -> nat) (F G : ufun) : ufun := fun x => d (F x) (G x).

(* the basis <S, Sq, O, Hf, Rt, F + G, F - G, FG, F^box> of Lemma 3.3 *)
Definition basisL33 (d : nat -> nat -> nat) : basis :=
  Basis (fun F => F = funS \/ F = funSq \/ F = funO \/ F = funHf \/ F = funRt)
        (fun u => u = opBox) (fun b => b = opPlus \/ b = opDiff d \/ b = comp).

(* Lemma 3.3, for every primitive recursive difference function.  The paper derives it
   from Lemma 3.1 and Theorem 2 of [15]; here it follows from Theorem 3 of [15] via
   E == I - Sq Rt. *)
Theorem Lemma_3_3 d : is_difference d -> PrimNN2 d -> suitable (basisL33 d).
Proof.
move=> hd hdP.
have E : Clos (basisL33 d) funE.
  have <- : opDiff d funI (funSq \o funRt) = funE.
    by apply: functional_extensionality => x; rewrite /opDiff hd //; apply: funRt_sq_le.
  by rewrite -funI_eq_box_S; clos_solve.
simulate Robinson_1947_sec7_thm3.
by move=> *; apply: pr_app2.
Qed.

(* The proof of the paper: the basis of Lemma 3.3 (with the difference function dE of
   footnote 8) is generated by F. *)
Theorem Theorem_6_7_via_L33 : suitable basis6.
Proof.
have hd : is_difference dE by move=> a b; exact: dE_diff.
have hdP : PrimNN2 dE.
  apply: pr_comp pr_E _.
  apply: pr_plus (pr_cst 1) => /=; apply: pr_plus pr_snd.
  apply: pr_plus (pr_mult (pr_cst 3) pr_fst).
  exact: pr_mult (pr_plus pr_fst pr_snd) (pr_plus pr_fst pr_snd).
have diff_in : forall F G, C6 F -> C6 G -> C6 (opDiff dE F G) by move=> *; exact: diffE_in.
by simulate (Lemma_3_3 hd hdP).
Qed.
